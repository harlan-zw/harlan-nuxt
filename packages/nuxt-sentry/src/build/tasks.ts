/**
 * Automatic failure reporting for Nitro scheduled tasks.
 *
 * Nitro's `runTask` calls no hook, so a plugin cannot observe a task run. What
 * Nitro does expose is the task registry: `nitro.options.tasks` maps every task
 * name to the module Nitro imports when the task runs. Pointing that entry at a
 * small virtual module, which imports the real task and wraps it with
 * `withSentryTask`, reports every task with no site code, including one a
 * module registers from inside its own package.
 *
 * Pure: takes the registry and returns the rewrite. The module applies it.
 */

/** The slice of a Nitro task registration this planner reads. */
export interface TaskRegistration {
  handler?: string
}

/** One task to rewrite: the virtual module to add, and the name whose handler becomes it. */
export interface TaskReportingPlan {
  name: string
  /** The virtual module id that becomes the task's handler. */
  id: string
  /** The virtual module's source. */
  code: string
}

const VIRTUAL_PREFIX = '#nuxt-sentry/tasks/'

/**
 * A task name as a module id segment.
 *
 * Nitro names a scanned task `dir:file`, and a colon reads as a scheme or a
 * drive letter to some resolvers.
 */
function slug(name: string): string {
  return name.replace(/[^\w.-]+/g, '-')
}

/** True for a handler this planner already rewrote. */
export function isReportingHandler(handler: string | undefined): boolean {
  return handler?.startsWith(VIRTUAL_PREFIX) ?? false
}

/**
 * Plans a wrapper for every registered task that has a handler.
 *
 * A task without a handler is skipped: Nitro warns about that itself. A task
 * already pointing at a wrapper is skipped, so a registry synced twice wraps
 * nothing twice. Two names that slug alike get distinct ids.
 */
export function planTaskReporting(tasks: Record<string, TaskRegistration>, wrapperModule: string): TaskReportingPlan[] {
  const used = new Set<string>()
  const plans: TaskReportingPlan[] = []
  for (const [name, task] of Object.entries(tasks)) {
    if (!task.handler || isReportingHandler(task.handler))
      continue
    let id = `${VIRTUAL_PREFIX}${slug(name)}`
    for (let n = 2; used.has(id); n++)
      id = `${VIRTUAL_PREFIX}${slug(name)}-${n}`
    used.add(id)
    plans.push({
      name,
      id,
      code: [
        '// Generated by @harlan-zw/nuxt-sentry. Wraps a Nitro task so a throw is reported before it leaves.',
        `import { withSentryTask } from ${JSON.stringify(wrapperModule)}`,
        `import task from ${JSON.stringify(task.handler)}`,
        '',
        'export default withSentryTask(task)',
        '',
      ].join('\n'),
    })
  }
  return plans
}
